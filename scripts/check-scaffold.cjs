const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { spawnSync } = require('node:child_process')
const root = path.resolve(__dirname, '..')
const sdk = path.join(root, 'sdk/.sdk')
const relative = 'src/cmp/ts/fragment/Config.fragment.ts'
const project = fs.readFileSync(path.join(sdk, relative), 'utf8')
const upstream = fs.readFileSync(path.join(sdk, 'node_modules/@voxgig/sdkgen/project/.sdk', relative), 'utf8').replaceAll('$$const.Name$$', 'EaFlood')
const addition = '\n    // Project default: station envelopes must be validated before conversion.\n    feature: { envelope: { active: true } },\n'
assert.equal(project.split(addition).length, 2, 'Expected exactly one reviewed envelope default')
assert.equal(project.replace(addition, ''), upstream, 'Unexpected configuration-fragment drift')
const result = spawnSync(process.platform === 'win32' ? 'npx.cmd' : 'npx', ['--no-install', 'voxgig-sdkgen', 'doctor'], { cwd: sdk, encoding: 'utf8' })
const output = (result.stdout || '') + (result.stderr || '')
process.stdout.write(output)
assert.equal(result.status, 1, 'Raw doctor must identify the documented single fork')
assert.match(output, /FORKED[^\n]*src\/cmp\/ts\/fragment\/Config\.fragment\.ts/)
assert.match(output, /1 forked, 0 edited, 0 stale, 0 missing, 0 outdated, 0 unresolved/)
const findings = output.split('\n').filter(line => line.includes('doctor-finding'))
assert.equal(findings.filter(line => !line.includes('additive') && !line.includes('Config.fragment.ts')).length, 0, 'Unexpected doctor finding')
console.log('PASS: one exact reviewed default-configuration fork; no unexpected scaffold drift')
